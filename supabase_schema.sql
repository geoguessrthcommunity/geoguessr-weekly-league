-- ====================================================================
-- SUPABASE DATABASE SCHEMA FOR GEOGUESSR WEEKLY CHALLENGES
-- วางโค้ดนี้ทั้งหมดใน Supabase: เมนู "SQL Editor" -> กด "New query" -> กด "Run"
-- (สามารถรันซ้ำได้ทั้งบนฐานข้อมูลใหม่และฐานข้อมูลเดิมที่มีข้อมูลอยู่แล้ว โดยไม่ลบข้อมูลเดิม)
-- ====================================================================

-- 1. ตารางเก็บข้อมูลสัปดาห์ (Weeks)
CREATE TABLE IF NOT EXISTS weeks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,                      -- เช่น "Week 1", "Cactus Ligue #11-06"
    header_info TEXT DEFAULT '',              -- ข้อมูลด้านบน เช่น "Du ven. 23 au ven. 30 octobre || You must play before..."
    is_active BOOLEAN NOT NULL DEFAULT false, -- สัปดาห์ปัจจุบันที่เปิดแข่งและแสดงหน้าแรก
    is_frozen BOOLEAN NOT NULL DEFAULT false, -- ฟรีซคะแนนแล้วหรือยัง (จบวีคแล้ว)
    start_date TIMESTAMPTZ,                   -- วัน-เวลาเริ่มต้นการแข่งขัน (ถ้ามี)
    end_date TIMESTAMPTZ,                     -- วัน-เวลาตัดรอบอัตโนมัติ
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE weeks ADD COLUMN IF NOT EXISTS start_date TIMESTAMPTZ;

-- 2. ตารางเก็บ Seed/Challenges ทั้งหมดในแต่ละสัปดาห์ (7 Maps, แต่ละ Map มีได้ตั้งแต่ 1 ถึงหลาย Seeds)
CREATE TABLE IF NOT EXISTS challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_id BIGINT NOT NULL REFERENCES weeks(id) ON DELETE CASCADE,
    seed_number INT NOT NULL DEFAULT 1,      -- คงไว้เพื่อความเข้ากันได้ย้อนหลัง (เก็บค่าเดียวกับ map_number)
    map_number INT NOT NULL CHECK (map_number BETWEEN 1 AND 7), -- ลำดับ Map ที่ 1 - 7
    sub_seed_number INT NOT NULL DEFAULT 1 CHECK (sub_seed_number >= 1), -- ลำดับ Seed ย่อยใน Map นั้น (1, 2, ...)
    game_type TEXT NOT NULL DEFAULT 'standard', -- 'standard' | 'country_count'
    name TEXT NOT NULL DEFAULT '',           -- รายละเอียด เช่น "Map 1 : Europe | NM - 1'"
    token TEXT DEFAULT '',                   -- รหัสโทเคนของ GeoGuessr (เว้นว่างได้ถ้ายังไม่สร้าง)
    url TEXT DEFAULT '',                     -- ลิงก์เต็มของ GeoGuessr Challenge (เว้นว่างได้)
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT challenges_week_map_subseed_unique UNIQUE(week_id, map_number, sub_seed_number)
);

-- อัปเกรดตาราง challenges กรณีเป็นฐานข้อมูลเดิม (ทำงานอัตโนมัติอย่างปลอดภัย)
ALTER TABLE challenges ALTER COLUMN token DROP NOT NULL;
ALTER TABLE challenges ALTER COLUMN token SET DEFAULT '';
ALTER TABLE challenges ALTER COLUMN url DROP NOT NULL;
ALTER TABLE challenges ALTER COLUMN url SET DEFAULT '';
ALTER TABLE challenges ADD COLUMN IF NOT EXISTS map_number INT;
ALTER TABLE challenges ADD COLUMN IF NOT EXISTS sub_seed_number INT NOT NULL DEFAULT 1;
ALTER TABLE challenges ADD COLUMN IF NOT EXISTS game_type TEXT NOT NULL DEFAULT 'standard';
UPDATE challenges SET map_number = seed_number WHERE map_number IS NULL;
ALTER TABLE challenges ALTER COLUMN map_number SET NOT NULL;
ALTER TABLE challenges DROP CONSTRAINT IF EXISTS challenges_seed_number_check;
ALTER TABLE challenges DROP CONSTRAINT IF EXISTS challenges_week_id_seed_number_key;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'challenges_week_map_subseed_unique'
  ) THEN
    ALTER TABLE challenges ADD CONSTRAINT challenges_week_map_subseed_unique UNIQUE (week_id, map_number, sub_seed_number);
  END IF;
END $$;

-- 3. ตารางเก็บผู้เล่นที่มีบัญชี GeoGuessr (Players)
CREATE TABLE IF NOT EXISTS players (
    id TEXT PRIMARY KEY,                     -- GeoGuessr User ID (24 hex chars)
    username TEXT NOT NULL,                  -- ชื่อเล่นล่าสุดของผู้เล่น
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. ตารางเก็บบันทึกคะแนน (Scores)
CREATE TABLE IF NOT EXISTS scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
    player_id TEXT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    r1 INT NOT NULL DEFAULT 0,               -- Standard: 0-5000 | Country Count: 0 หรือ 1
    r2 INT NOT NULL DEFAULT 0,
    r3 INT NOT NULL DEFAULT 0,
    r4 INT NOT NULL DEFAULT 0,
    r5 INT NOT NULL DEFAULT 0,
    total_score INT NOT NULL DEFAULT 0,      -- Standard: 0-25000 | Country Count: 0-5
    played_at TIMESTAMPTZ,                   -- เวลาที่ผู้เล่นเล่นจบ
    total_time INT,                          -- เวลารวมที่ใช้เล่น (วินาที)
    round_details JSONB,                     -- รายละเอียดเสริมรายรอบ (เช่น target/guess country)
    is_manual BOOLEAN NOT NULL DEFAULT false,-- ป้องกัน Sync เขียนทับคะแนนที่แอดมินแก้ด้วยมือ
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(challenge_id, player_id)
);

ALTER TABLE scores ADD COLUMN IF NOT EXISTS played_at TIMESTAMPTZ;
ALTER TABLE scores ADD COLUMN IF NOT EXISTS total_time INT;
ALTER TABLE scores ADD COLUMN IF NOT EXISTS round_details JSONB;
ALTER TABLE scores ADD COLUMN IF NOT EXISTS is_manual BOOLEAN NOT NULL DEFAULT false;

-- 5. ตารางกฎปรับแก้คะแนนกรณีหมุดมีปัญหา / ชดเชยคะแนน (Score Adjustment Rules)
CREATE TABLE IF NOT EXISTS score_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
    round_number INT NOT NULL CHECK (round_number BETWEEN 1 AND 5),
    rule_type TEXT NOT NULL DEFAULT 'threshold_to_max', -- 'threshold_to_max', 'void_round', 'bonus_points'
    min_score INT NOT NULL DEFAULT 4990,                -- คะแนนขั้นต่ำที่จะปรับเป็น target_score
    target_score INT NOT NULL DEFAULT 5000,             -- คะแนนเป้าหมายที่มอบให้ (เช่น 5,000)
    bonus_points INT NOT NULL DEFAULT 0,                -- แต้มบวกชดเชยพิเศษ
    note TEXT DEFAULT '',                               -- บันทึกเหตุผล เช่น "หมุดคลาดเคลื่อน 20 เมตร"
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(challenge_id, round_number)
);

-- 6. ตารางคิวคำขอ Sync ทันที (Force Sync Requests)
CREATE TABLE IF NOT EXISTS sync_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'pending',             -- 'pending', 'processing', 'completed', 'failed'
    requested_by TEXT DEFAULT 'admin',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);

-- 7. ตารางรายชื่อผู้เล่นที่ถูกตัดสิทธิ์ประจำสัปดาห์ (Disqualified Players)
-- ป้องกันไม่ให้ระบบ Auto-Sync ดึงคะแนนของคนที่ถูกแอดมิน DQ กลับเข้ามาซ้ำ
CREATE TABLE IF NOT EXISTS disqualified_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_id BIGINT NOT NULL REFERENCES weeks(id) ON DELETE CASCADE,
    player_id TEXT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    reason TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(week_id, player_id)
);

-- สร้าง Indexes
CREATE INDEX IF NOT EXISTS idx_challenges_week_id ON challenges(week_id);
CREATE INDEX IF NOT EXISTS idx_challenges_map_subseed ON challenges(week_id, map_number, sub_seed_number);
CREATE INDEX IF NOT EXISTS idx_scores_challenge_id ON scores(challenge_id);
CREATE INDEX IF NOT EXISTS idx_scores_player_id ON scores(player_id);
CREATE INDEX IF NOT EXISTS idx_adjustments_challenge_id ON score_adjustments(challenge_id);
CREATE INDEX IF NOT EXISTS idx_sync_requests_status ON sync_requests(status);
CREATE INDEX IF NOT EXISTS idx_dq_week_id ON disqualified_players(week_id);

-- เปิดระบบ Row Level Security (RLS)
ALTER TABLE weeks ENABLE ROW LEVEL SECURITY;
ALTER TABLE challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE score_adjustments ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE disqualified_players ENABLE ROW LEVEL SECURITY;

