-- ====================================================================
-- SUPABASE DATABASE SCHEMA FOR GEOGUESSR WEEKLY CHALLENGES
-- วางโค้ดนี้ใน Supabase: เมนู "SQL Editor" -> กด "New query" -> แล้วกด "Run"
-- ====================================================================

-- 1. ตารางเก็บข้อมูลสัปดาห์ (Weeks)
CREATE TABLE IF NOT EXISTS weeks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,                      -- เช่น "Week 1", "Cactus Ligue #11-06"
    header_info TEXT DEFAULT '',              -- ข้อมูลด้านบน เช่น "Du ven. 23 au ven. 30 octobre || You must play before..."
    is_active BOOLEAN NOT NULL DEFAULT true,  -- สัปดาห์ปัจจุบันที่แสดงหน้าแรก
    is_frozen BOOLEAN NOT NULL DEFAULT false, -- ฟรีซคะแนนแล้วหรือยัง (จบวีคแล้ว)
    end_date TIMESTAMPTZ,                     -- วัน-เวลาตัดรอบอัตโนมัติ
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. ตารางเก็บ Seed/Challenges ทั้งหมดในแต่ละสัปดาห์ (7 Seeds)
CREATE TABLE IF NOT EXISTS challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_id BIGINT NOT NULL REFERENCES weeks(id) ON DELETE CASCADE,
    seed_number INT NOT NULL CHECK (seed_number BETWEEN 1 AND 7), -- ลำดับที่ 1 - 7
    name TEXT NOT NULL DEFAULT '',           -- รายละเอียด เช่น "Map 1 : Europe | NM - 1'"
    token TEXT NOT NULL,                     -- รหัสโทเคนของ GeoGuessr (16 ตัวอักษร)
    url TEXT NOT NULL,                       -- ลิงก์เต็มของ GeoGuessr Challenge
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(week_id, seed_number)
);

-- 3. ตารางเก็บผู้เล่นที่มีบัญชี GeoGuessr (Players)
CREATE TABLE IF NOT EXISTS players (
    id TEXT PRIMARY KEY,                     -- GeoGuessr User ID (24 hex chars)
    username TEXT NOT NULL,                  -- ชื่อเล่นล่าสุดของผู้เล่น
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. ตารางเก็บบันทึกคะแนน (Scores)
CREATE TABLE IF NOT EXISTS scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
    player_id TEXT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    r1 INT NOT NULL DEFAULT 0,               -- คะแนน Round 1 (0 - 5000)
    r2 INT NOT NULL DEFAULT 0,               -- คะแนน Round 2 (0 - 5000)
    r3 INT NOT NULL DEFAULT 0,               -- คะแนน Round 3 (0 - 5000)
    r4 INT NOT NULL DEFAULT 0,               -- คะแนน Round 4 (0 - 5000)
    r5 INT NOT NULL DEFAULT 0,               -- คะแนน Round 5 (0 - 5000)
    total_score INT NOT NULL DEFAULT 0,      -- คะแนนรวมของ Seed นั้น (0 - 25,000)
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(challenge_id, player_id)
);

-- 5. ตารางกฎปรับแก้คะแนนกรณีหมุดมีปัญหา / ชดเชยคะแนน (Score Adjustment Rules)
CREATE TABLE IF NOT EXISTS score_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
    round_number INT NOT NULL CHECK (round_number BETWEEN 1 AND 5),
    rule_type TEXT NOT NULL DEFAULT 'threshold_to_max', -- 'threshold_to_max', 'void_round', 'bonus_points'
    min_score INT NOT NULL DEFAULT 4990,                -- คะแนนขั้นต่ำที่จะปรับเป็น target_score
    target_score INT NOT NULL DEFAULT 5000,             -- คะแนนเป้าหมายที่มอบให้ (เช่น 5,000)
    bonus_points INT NOT NULL DEFAULT 0,                -- แต้มบวกชดเชยพิเศษ
    note TEXT DEFAULT '',                               -- บันทึกเหตุผล เช่น "หมุดคลาดเคลื่อน 20 เมตร"
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(challenge_id, round_number)
);

-- 6. ตารางคิวคำขอ Sync ทันที (Force Sync Requests)
CREATE TABLE IF NOT EXISTS sync_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'pending',             -- 'pending', 'processing', 'completed', 'failed'
    requested_by TEXT DEFAULT 'admin',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);

-- สร้าง Indexes
CREATE INDEX IF NOT EXISTS idx_challenges_week_id ON challenges(week_id);
CREATE INDEX IF NOT EXISTS idx_scores_challenge_id ON scores(challenge_id);
CREATE INDEX IF NOT EXISTS idx_scores_player_id ON scores(player_id);
CREATE INDEX IF NOT EXISTS idx_adjustments_challenge_id ON score_adjustments(challenge_id);
CREATE INDEX IF NOT EXISTS idx_sync_requests_status ON sync_requests(status);

-- เปิดระบบ Row Level Security (RLS)
ALTER TABLE weeks ENABLE ROW LEVEL SECURITY;
ALTER TABLE challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE score_adjustments ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_requests ENABLE ROW LEVEL SECURITY;

-- นโยบายให้อ่านข้อมูลได้แบบ Public (สำหรับหน้าเว็บ Netlify ผ่าน Anon Key)
CREATE POLICY "Allow public read on weeks" ON weeks FOR SELECT USING (true);
CREATE POLICY "Allow public read on challenges" ON challenges FOR SELECT USING (true);
CREATE POLICY "Allow public read on players" ON players FOR SELECT USING (true);
CREATE POLICY "Allow public read on scores" ON scores FOR SELECT USING (true);
CREATE POLICY "Allow public read on score_adjustments" ON score_adjustments FOR SELECT USING (true);
CREATE POLICY "Allow public read on sync_requests" ON sync_requests FOR SELECT USING (true);
